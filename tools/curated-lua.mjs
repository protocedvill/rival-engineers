// Curated modules (data/modules/*.json, SPEC §5.4) as one Lua table: modules/curated_data.lua. Used by the mod build
// (tools/build-mod.mjs) and the T1 runner (tools/run-unit-tests.mjs: the B25 belt-edge check covers curated modules).
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"

function toLua(v, indent = "") {
  if (v === null || v === undefined) return "nil"
  if (typeof v === "number") return String(v)
  if (typeof v === "boolean") return String(v)
  if (typeof v === "string") return JSON.stringify(v)
  const inner = indent + " "
  if (Array.isArray(v)) return "{" + v.map((x) => toLua(x, inner)).join(", ") + "}"
  const parts = Object.keys(v)
    .sort()
    .map((k) => `[${JSON.stringify(k)}] = ${toLua(v[k], inner)}`)
  return "{\n" + inner + parts.join(",\n" + inner) + "\n" + indent + "}"
}

/** Writes `outFile` from every data/modules/*.json under `root`. */
export function writeCuratedLua(root, outFile) {
  const dataDir = join(root, "data", "modules")
  const curated = {}
  for (const f of readdirSync(dataDir).filter((f) => f.endsWith(".json")).sort()) {
    const m = JSON.parse(readFileSync(join(dataDir, f), "utf8"))
    curated[m.id] = m
  }
  mkdirSync(dirname(outFile), { recursive: true })
  writeFileSync(outFile, "-- generated by tools/curated-lua.mjs from data/modules/*.json\nreturn " + toLua(curated) + "\n")
}
