// Builds the mod into mod/build: transpiles both TS stages and copies static files.
import { execFileSync } from "node:child_process"
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const mod = join(root, "mod")
const tstl = join(root, "node_modules", ".bin", "tstl")

rmSync(join(mod, "build"), { recursive: true, force: true })
for (const project of ["tsconfig.json", "tsconfig.settings.json"]) {
  execFileSync(tstl, ["-p", join(mod, project)], { stdio: "inherit" })
}
cpSync(join(mod, "static"), join(mod, "build"), { recursive: true })

// Curated modules (data/modules/*.json, SPEC §5.4) become one Lua table: modules/curated_data.lua.
function toLua(v, indent = "") {
  if (v === null || v === undefined) return "nil"
  if (typeof v === "number") return Number.isInteger(v) ? String(v) : String(v)
  if (typeof v === "boolean") return String(v)
  if (typeof v === "string") return JSON.stringify(v)
  const inner = indent + " "
  if (Array.isArray(v)) return "{" + v.map((x) => toLua(x, inner)).join(", ") + "}"
  const parts = Object.keys(v)
    .sort()
    .map((k) => `[${JSON.stringify(k)}] = ${toLua(v[k], inner)}`)
  return "{\n" + inner + parts.join(",\n" + inner) + "\n" + indent + "}"
}
const dataDir = join(root, "data", "modules")
const curated = {}
for (const f of readdirSync(dataDir).filter((f) => f.endsWith(".json")).sort()) {
  const m = JSON.parse(readFileSync(join(dataDir, f), "utf8"))
  curated[m.id] = m
}
mkdirSync(join(mod, "build", "modules"), { recursive: true })
writeFileSync(join(mod, "build", "modules", "curated_data.lua"), "-- generated by tools/build-mod.mjs from data/modules/*.json\nreturn " + toLua(curated) + "\n")
console.log("built mod/build")
