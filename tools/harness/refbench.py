#!/usr/bin/env python3
"""Reference-save benchmark (SPEC §9 performance gates, backlog B10): AI time as a percentage of the update time of a
fixed vanilla mid-game base, measured in the same session, so the number means the same on any machine and load.

The reference base is generated by a script (no licensing question, reproducible): a fresh map (seed 1, no biters),
then `--cells` copies of one cell built by script on flattened grass, run 10 game-minutes to settle, then saved. A cell
is 7 electric drills on iron ore → belt → 10 electric furnaces → plate belt → infinity-chest sinks; 10 assembling
machine 2 making gears from infinity chests through fast inserters; a 2×40 belt loop full of moving plates; substations.
An electric-energy-interface powers it (a real steam block adds a little fluid update time; noted, not modelled).
The default 48 cells are ~12,000 built entities (plus ~9,000 ore tiles), about a 60-90 SPM pre-bot base by entity
count.

Usage:
  python3 tools/harness/refbench.py generate [--cells 24]          # once: .factorio-test/refbench/reference.zip
  python3 tools/harness/refbench.py bench [--ticks 6000] [--runs 3] # the reference's update ms/tick
  python3 tools/harness/refbench.py report out/soak/<run>           # bench now, then each seed's AI ms/tick as % of it
  python3 tools/harness/refbench.py session -c tools/harness/m5-mall.toml --seeds 11 --name ref-11
                                    # bench, soak at -j 1, bench again; AI % of the mean reference time

Run it on an idle machine: concurrent Factorio instances inflate both numbers differently.
"""
import argparse
import json
import re
import shutil
import statistics
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FACTORIO = ROOT / ".factorio-test" / "factorio" / "bin" / "x64" / "factorio"
READ_DATA = ROOT / ".factorio-test" / "factorio" / "data"
DIR = ROOT / ".factorio-test" / "refbench"
SAVE = DIR / "reference.zip"
BENCH = re.compile(r"Performed (\d+) updates in ([0-9.]+) ms")
WARMUP_TICKS = 36000  # 10 game-minutes: belts fill, furnaces and assemblers reach a steady state before the save

BUILD_LUA = r"""
local CELLS = %(cells)d
local X0, Y0 = 2000, -200
local function build()
  local s = game.surfaces[1]
  local w, h = 100, CELLS / 2 * 30 + 20
  s.request_to_generate_chunks({X0 + w / 2, Y0 + h / 2}, math.ceil(math.max(w, h) / 64) + 2)
  s.force_generate_chunk_requests()
  local area = {{X0 - 10, Y0 - 10}, {X0 + w + 10, Y0 + h + 10}}
  for _, e in pairs(s.find_entities_filtered{area = area}) do if e.valid and e.type ~= "character" then e.destroy() end end
  local tiles = {}
  for x = X0 - 10, X0 + w + 10 do for y = Y0 - 10, Y0 + h + 10 do tiles[#tiles + 1] = {name = "grass-1", position = {x, y}} end end
  s.set_tiles(tiles)
  local f = "player"
  local function put(name, x, y, dir, extra)
    local p = {name = name, position = {x, y}, direction = dir, force = f}
    if extra then for k, v in pairs(extra) do p[k] = v end end
    local e = s.create_entity(p)
    if not e then error("could not place " .. name .. " at " .. x .. "," .. y) end
    return e
  end
  local N, E, S, W = defines.direction.north, defines.direction.east, defines.direction.south, defines.direction.west
  local function sink(x, y) local c = put("infinity-chest", x, y); c.remove_unfiltered_items = true; return c end
  local function source(x, y, item) local c = put("infinity-chest", x, y); c.set_infinity_container_filter(1, {name = item, count = 50, mode = "exactly", index = 1}); return c end
  local eei = put("electric-energy-interface", X0 - 4, Y0 + 1)
  eei.power_production = 1e9 / 60
  eei.electric_buffer_size = 1e9
  put("substation", X0 - 1, Y0 + 1)
  for c = 0, CELLS - 1 do
    local X = X0 + (c %% 2) * 50
    local Y = Y0 + math.floor(c / 2) * 30
    for x = X, X + 36 do for y = Y, Y + 4 do s.create_entity{name = "iron-ore", position = {x + 0.5, y + 0.5}, amount = 10000000} end end
    for k = 0, 6 do put("electric-mining-drill", X + 1.5 + 5 * k, Y + 1.5, S) end
    for _, gx in pairs({X + 3, X + 18, X + 33, X + 45}) do put("substation", gx + 1, Y + 1); put("substation", gx + 1, Y + 18) end
    for x = X, X + 40 do put("transport-belt", x + 0.5, Y + 3.5, E) end
    put("inserter", X + 41.5, Y + 3.5, W); sink(X + 42.5, Y + 3.5)
    for j = 0, 9 do
      local cx = X + 8.5 + 3 * j
      put("inserter", cx, Y + 4.5, N)
      put("electric-furnace", cx, Y + 6.5)
      put("inserter", cx, Y + 8.5, N)
    end
    for x = X + 7, X + 40 do put("transport-belt", x + 0.5, Y + 9.5, E) end
    put("inserter", X + 41.5, Y + 9.5, W); sink(X + 42.5, Y + 9.5)
    for x = X + 38, X + 40 do put("fast-inserter", x + 0.5, Y + 10.5, N); sink(x + 0.5, Y + 11.5) end
    for k = 0, 9 do
      local cx = X + 1.5 + 4 * k
      source(cx, Y + 10.5, "iron-plate")
      put("fast-inserter", cx, Y + 11.5, N)
      put("assembling-machine-2", cx, Y + 13.5, nil, {recipe = "iron-gear-wheel"})
      put("fast-inserter", cx, Y + 15.5, N)
      sink(cx, Y + 16.5)
    end
    for x = X, X + 39 do put("transport-belt", x + 0.5, Y + 20.5, E) end
    put("transport-belt", X + 40.5, Y + 20.5, S)
    for x = X + 1, X + 40 do put("transport-belt", x + 0.5, Y + 21.5, W) end
    put("transport-belt", X + 0.5, Y + 21.5, N)
    for _, e in pairs(s.find_entities_filtered{area = {{X, Y + 20}, {X + 41, Y + 22}}, type = "transport-belt"}) do
      for l = 1, 2 do e.get_transport_line(l).insert_at(0.25, {name = "iron-plate", count = 1}) end
    end
  end
  storage.refbase = {built = game.tick, entities = s.count_entities_filtered{area = area}}
  log("[refbench] built " .. CELLS .. " cells, " .. storage.refbase.entities .. " entities")
end
script.on_event(defines.events.on_tick, function(e)
  if storage.refbase == nil then
    build()
    if game.is_multiplayer() then game.speed = 1000 end
  elseif storage.refbase.saved == nil and e.tick >= storage.refbase.built + %(warmup)d then
    storage.refbase.saved = e.tick
    local s = game.surfaces[1]
    local counts = {}
    local hist = {}
    for _, t in pairs({"mining-drill", "furnace", "assembling-machine", "inserter"}) do
      local n, working = 0, 0
      for _, m in pairs(s.find_entities_filtered{type = t, force = "player"}) do
        n = n + 1
        if m.status == defines.entity_status.working then working = working + 1 end
        local st = tostring(m.status)
        for k, v in pairs(defines.entity_status) do if v == m.status then st = k end end
        hist[t .. ":" .. st] = (hist[t .. ":" .. st] or 0) + 1
      end
      counts[#counts + 1] = t .. " " .. working .. "/" .. n
    end
    log("[refbench] working after warm-up: " .. table.concat(counts, ", "))
    log("[refbench] statuses: " .. serpent.line(hist))
    game.server_save("reference")
  end
end)
"""


def setup(cells):
    """The write-data dir: base game plus the reference helper mod (kept for benchmarking: the save lists it)."""
    data = DIR / "data"
    mods = data / "mods"
    mods.mkdir(parents=True, exist_ok=True)
    (data / "saves").mkdir(exist_ok=True)
    (DIR / "config.ini").write_text(f"[path]\nread-data={READ_DATA}\nwrite-data={data}\n")
    helper = mods / "rival-engineers-refbase"
    shutil.rmtree(helper, ignore_errors=True)
    helper.mkdir()
    (helper / "info.json").write_text(json.dumps({"name": "rival-engineers-refbase", "version": "0.0.1",
                                                  "title": "Rival Engineers reference base", "author": "harness",
                                                  "factorio_version": "2.0", "dependencies": ["base"]}))
    (helper / "control.lua").write_text(BUILD_LUA % {"cells": cells, "warmup": WARMUP_TICKS})
    mod_list = {"mods": [{"name": n, "enabled": e} for n, e in [("base", True), ("elevated-rails", False), ("quality", False),
                                                                 ("space-age", False), ("rival-engineers-refbase", True)]]}
    (mods / "mod-list.json").write_text(json.dumps(mod_list, indent=1))
    return DIR / "config.ini"


def generate(cells):
    conf = str(setup(cells))
    data = DIR / "data"
    fresh = DIR / "fresh.zip"
    mgs = DIR / "map-gen-settings.json"
    mgs.write_text(json.dumps({"autoplace_controls": {"enemy-base": {"frequency": 0, "size": 0, "richness": 0}}}))
    for p in (fresh, data / "saves" / "reference.zip"):
        p.unlink(missing_ok=True)
    subprocess.run([str(FACTORIO), "-c", conf, "--create", str(fresh), "--map-gen-settings", str(mgs), "--map-gen-seed", "1"],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT)
    ss = json.loads((READ_DATA / "server-settings.example.json").read_text())
    ss.update(visibility={"public": False, "lan": False}, require_user_verification=False, auto_pause=False,
              autosave_interval=100000, autosave_slots=1)
    (DIR / "server-settings.json").write_text(json.dumps(ss))
    out = data / "saves" / "reference.zip"
    with open(DIR / "generate.log", "w") as log:
        proc = subprocess.Popen([str(FACTORIO), "-c", conf, "--start-server", str(fresh), "--server-settings",
                                 str(DIR / "server-settings.json"), "--port", "34190", "--bind", "127.0.0.1"],
                                stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.PIPE)
        size = -1
        while proc.poll() is None:
            time.sleep(2)
            if out.exists():
                s = out.stat().st_size
                if s == size and s > 0:
                    break
                size = s
        proc.kill()
        proc.wait()
    if not out.exists():
        sys.exit(f"no reference save written; see {DIR / 'generate.log'} and {data / 'factorio-current.log'}")
    shutil.copy(out, SAVE)
    text = (data / "factorio-current.log").read_text(errors="replace")
    found = re.findall(r"\[refbench\] .*", text)
    print(f"reference save: {SAVE}\n  " + "\n  ".join(found))


def bench(ticks, runs):
    if not SAVE.exists():
        sys.exit("no reference save: run `refbench.py generate` first")
    conf = str(setup_existing())
    times = []
    for _ in range(runs):
        r = subprocess.run([str(FACTORIO), "-c", conf, "--benchmark", str(SAVE), "--benchmark-ticks", str(ticks),
                            ], capture_output=True, text=True)
        m = BENCH.search(r.stdout)
        if not m:
            sys.exit(f"benchmark failed:\n{r.stdout[-2000:]}")
        times.append(float(m.group(2)) / int(m.group(1)))
    return {"ms_per_tick": statistics.median(times), "runs": [round(t, 4) for t in times], "ticks": ticks}


def setup_existing():
    conf = DIR / "config.ini"
    if not conf.exists():
        sys.exit("refbench not set up: run `refbench.py generate`")
    return conf


def ai_per_seed(run_dir):
    sc = Path(run_dir) / "scorecard.json"
    if not sc.exists():
        sys.exit(f"{sc} not found")
    out = {}
    doc = json.loads(sc.read_text())
    for r in doc.get("results", []):
        out[r["seed"]] = {"ai": r.get("ai_ms_per_tick_avg"), "p99": r.get("ai_ms_per_tick_p99_interval")}
    return out, (doc.get("config") or {}).get("run", {}).get("jobs")


def report(run_dir, ref, ref_after=None):
    seeds, jobs = ai_per_seed(run_dir)
    refs = [ref["ms_per_tick"]] + ([ref_after["ms_per_tick"]] if ref_after else [])
    base = statistics.mean(refs)
    lines = [f"Reference base update: {base:.3f} ms/tick (runs {', '.join(f'{x:.3f}' for x in refs)})",
             f"Mod run {Path(run_dir).name} (soak -j {jobs}{'' if jobs == 1 else ': concurrent runs inflate AI time'}):"]
    for seed, v in seeds.items():
        if v["ai"] is None:
            continue
        lines.append(f"  seed {seed}: AI {v['ai']:.3f} ms/tick = {100 * v['ai'] / base:.1f}% of the reference update"
                     f" (p99 minute {v['p99']:.3f} = {100 * v['p99'] / base:.1f}%)")
    doc = {"run": str(run_dir), "reference_ms_per_tick": base, "reference_runs": refs, "jobs": jobs,
           "seeds": {s: {**v, "pct": round(100 * v["ai"] / base, 2) if v["ai"] else None} for s, v in seeds.items()}}
    (Path(run_dir) / "refbench.json").write_text(json.dumps(doc, indent=1))
    print("\n".join(lines))


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate")
    g.add_argument("--cells", type=int, default=48)
    for name in ("bench", "report", "session"):
        p = sub.add_parser(name)
        p.add_argument("--ticks", type=int, default=6000)
        p.add_argument("--runs", type=int, default=3)
        if name == "report":
            p.add_argument("run")
        if name == "session":
            p.add_argument("-c", "--config", required=True)
            p.add_argument("--seeds", required=True)
            p.add_argument("--name", required=True)
    a = ap.parse_args(argv)
    if a.cmd == "generate":
        generate(a.cells)
    elif a.cmd == "bench":
        print(json.dumps(bench(a.ticks, a.runs)))
    elif a.cmd == "report":
        report(a.run, bench(a.ticks, a.runs))
    else:
        before = bench(a.ticks, a.runs)
        subprocess.run([sys.executable, str(ROOT / "tools" / "harness" / "soak.py"), "-c", a.config, "--seeds", a.seeds,
                        "--name", a.name, "-j", "1"], check=True)
        after = bench(a.ticks, a.runs)
        report(ROOT / "out" / "soak" / a.name, before, after)


if __name__ == "__main__":
    main(sys.argv[1:])
